//! 给 NSH JS/TSX 插件生成 `.nsh/types/` 与 `.nsh/tsconfig.json`，与宿主真实导出的模块、
//! Smelt 主题色令牌、自带 SVG 图标路径以及守护 Control 方法保持完全一致。

use std::{
    collections::BTreeMap,
    fmt::Write as _,
    fs,
    path::{Path, PathBuf},
};

use gpui::AssetSource as _;
use smelt_plugin_api::client::protocol::control::ControlMethod;

/// 插件根目录的 `tsconfig.json`：继承 Smelt 生成的 `.nsh/tsconfig.json`。
pub const PLUGIN_TSCONFIG: &str = r#"{
  "extends": "./.nsh/tsconfig.json",
  "include": ["**/*.ts", "**/*.tsx"]
}
"#;

/// `.nsh/tsconfig.json`：把 `nsh`、`nsh/*` 与 `smelt/*` 指向 `.nsh/types/`。
pub const PLUGIN_TSCONFIG_BASE: &str = r#"// Generated by smelt plugin types: do not edit.
{
  "compilerOptions": {
    "target": "ES2023",
    "lib": ["ES2023", "ESNext.Disposable"],
    "module": "ESNext",
    "moduleResolution": "Bundler",
    "jsx": "preserve",
    "jsxImportSource": "nsh",
    "strict": true,
    "noEmit": true,
    "isolatedModules": true,
    "skipLibCheck": true,
    "types": [],
    "paths": {
      "nsh": ["./types/nsh/index.d.ts"],
      "nsh/*": ["./types/nsh/*.d.ts"],
      "smelt/*": ["./types/smelt/*.d.ts"],
      "*": ["./types/*.d.ts"]
    }
  },
  "files": [
    "./types/nsh/globals.d.ts",
    "./types/nsh/tokens.d.ts"
  ]
}
"#;

const SDK_DECL: &str = include_str!("plugins/sdk.d.ts");

/// Guest 插件实际可 import 的 NSH `.d.ts` 路径（过滤掉未开放的标准库、mobile 和 web 模块）。
const ALLOWED_NSH_FILES: &[&str] = &[
    "nsh/index.d.ts",
    "nsh/types.d.ts",
    "nsh/base.d.ts",
    "nsh/desktop.d.ts",
    "nsh/i18n.d.ts",
    "nsh/jsx-runtime.d.ts",
    "nsh/globals.d.ts",
    "smelt/host.d.ts",
];

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct TypesWriteReport {
    pub types_dir: PathBuf,
    pub files_written: usize,
    pub files_unchanged: usize,
    pub created_tsconfig: bool,
}

/// 生成插件可用的 `.d.ts` 文件表：`(相对 .nsh/types/ 的路径, 内容)`，并包含 `sources` 里发现的共享模块插件类型声明。
pub fn plugin_type_definitions(sources: &[crate::manifest::SourceDir]) -> Vec<(String, String)> {
    let mut files: BTreeMap<String, String> = nsh_js::type_definitions(&crate::ui_sets())
        .into_iter()
        .filter(|(path, _)| ALLOWED_NSH_FILES.contains(&path.as_str()))
        .map(|(path, body)| {
            let body = if path == "nsh/globals.d.ts" {
                clean_globals(&body)
            } else {
                body
            };
            (path, body)
        })
        .collect();

    let tokens = crate::theme::nsh_theme().into_tokens();
    files.insert(
        "nsh/tokens.d.ts".to_owned(),
        nsh_bundler::tokens_declaration(&tokens),
    );
    files.insert("smelt/sdk.d.ts".to_owned(), sdk_declaration());

    for pkg in crate::manifest::discover_module_packages(sources) {
        let Some(types_rel) = pkg.types.as_deref() else {
            continue;
        };
        let path = pkg.root.join(types_rel);
        match fs::read_to_string(&path) {
            Ok(body) => {
                files.insert(format!("{}.d.ts", pkg.specifier), body);
            }
            Err(error) => {
                eprintln!(
                    "[smelt-nsh] 读取共享模块声明 {} 失败：{error}",
                    path.display()
                );
            }
        }
    }

    files.into_iter().collect()
}

/// 把 `.nsh/types/`、`.nsh/tsconfig.json` 和（若缺失）`tsconfig.json` 写进插件目录 `dir`。
pub fn write_plugin_types(
    dir: &Path,
    sources: &[crate::manifest::SourceDir],
) -> Result<TypesWriteReport, String> {
    let definitions = plugin_type_definitions(sources);
    let types_dir = dir.join(".nsh/types");
    remove_stale(&types_dir, &types_dir, &definitions);

    let mut files_written = 0;
    let mut files_unchanged = 0;

    let items = definitions
        .iter()
        .map(|(rel, body)| (types_dir.join(rel), body.as_str()))
        .chain([(dir.join(".nsh/tsconfig.json"), PLUGIN_TSCONFIG_BASE)]);

    for (path, body) in items {
        if fs::read(&path).is_ok_and(|old| old == body.as_bytes()) {
            files_unchanged += 1;
            continue;
        }
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent)
                .map_err(|error| format!("创建 {} 失败：{error}", parent.display()))?;
        }
        fs::write(&path, body).map_err(|error| format!("写入 {} 失败：{error}", path.display()))?;
        files_written += 1;
    }

    let tsconfig = dir.join("tsconfig.json");
    let created_tsconfig = if !tsconfig.exists() {
        fs::write(&tsconfig, PLUGIN_TSCONFIG)
            .map_err(|error| format!("写入 {} 失败：{error}", tsconfig.display()))?;
        true
    } else {
        false
    };

    Ok(TypesWriteReport {
        types_dir,
        files_written,
        files_unchanged,
        created_tsconfig,
    })
}

fn sdk_declaration() -> String {
    let mut out = String::from("// Generated by smelt plugin types: do not edit.\n\n");
    out.push_str(SDK_DECL);
    if !out.ends_with('\n') {
        out.push('\n');
    }

    let mut icons: Vec<String> = smelt_ui::assets::Assets
        .list("")
        .unwrap_or_default()
        .into_iter()
        .map(|s| s.to_string())
        .collect();
    icons.sort_unstable();
    icons.dedup();
    write_string_union(
        &mut out,
        "/** Built-in SVG icon asset paths shipped by Smelt (`icons/*.svg`, `smelt-icons/*.svg`). */",
        "SmeltIconPath",
        icons.iter().map(String::as_str),
    );

    let mut methods: Vec<&'static str> = ControlMethod::ALL.iter().map(|m| m.as_str()).collect();
    methods.sort_unstable();
    methods.dedup();
    write_string_union(
        &mut out,
        "/** Control API RPC method names served by `smeltd`. */",
        "ControlMethodName",
        methods,
    );

    out
}

fn write_string_union<'a>(
    out: &mut String,
    doc: &str,
    name: &str,
    values: impl IntoIterator<Item = &'a str>,
) {
    let _ = writeln!(out, "\n{doc}");
    let _ = writeln!(out, "export type {name} =");
    let mut empty = true;
    for value in values {
        empty = false;
        let escaped = serde_json::to_string(value).unwrap_or_else(|_| "\"\"".to_owned());
        let _ = writeln!(out, "  | {escaped}");
    }
    if empty {
        out.push_str("  never;\n");
    } else {
        out.pop();
        out.push_str(";\n");
    }
}

/// 去掉未对插件开放的 `standard/index.d.ts` 引用以及 `standard::declarations::globals()` 插入的
/// `Buffer` / `process` / `crypto` 标准全局声明。
fn clean_globals(raw: &str) -> String {
    let lines: Vec<&str> = raw.lines().collect();
    let mut out = String::with_capacity(raw.len());
    let mut i = 0;
    while i < lines.len() {
        let line = lines[i];
        if line == "/// <reference path=\"../standard/index.d.ts\" />" {
            i += 1;
            continue;
        }
        if line == "/** Runtime constructor without an upstream constructor signature. */"
            && lines.get(i + 1).is_some_and(|next| {
                next.starts_with("declare const Crypto:")
                    || next.starts_with("declare const CryptoKey:")
                    || next.starts_with("declare const SubtleCrypto:")
            })
        {
            i += 2;
            continue;
        }
        if line.starts_with("declare var Buffer:")
            || line.starts_with("type Buffer = import(\"buffer\")")
            || line.starts_with("declare var process:")
            || line.starts_with("declare var crypto:")
            || line.starts_with("declare const Crypto:")
            || line.starts_with("declare const CryptoKey:")
            || line.starts_with("declare const SubtleCrypto:")
        {
            i += 1;
            continue;
        }
        out.push_str(line);
        out.push('\n');
        i += 1;
    }
    out
}

/// 清掉 `.nsh/types/` 里已不再生成的旧文件与空目录。
fn remove_stale(types: &Path, dir: &Path, definitions: &[(String, String)]) {
    let Ok(entries) = fs::read_dir(dir) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            remove_stale(types, &path, definitions);
            let _ = fs::remove_dir(&path);
        } else if let Ok(relative) = path.strip_prefix(types) {
            let relative = relative.to_string_lossy().replace('\\', "/");
            if !definitions.iter().any(|(p, _)| *p == relative) {
                let _ = fs::remove_file(&path);
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use oxc::{
        allocator::Allocator,
        ast::ast::{BindingPattern, Declaration, Statement},
        parser::Parser,
        span::SourceType,
    };
    use std::collections::BTreeSet;

    fn collect_binding(pattern: &BindingPattern<'_>, out: &mut BTreeSet<String>) {
        match pattern {
            BindingPattern::BindingIdentifier(id) => {
                out.insert(id.name.as_str().to_owned());
            }
            BindingPattern::ObjectPattern(obj) => {
                for prop in &obj.properties {
                    collect_binding(&prop.value, out);
                }
                if let Some(rest) = &obj.rest {
                    collect_binding(&rest.argument, out);
                }
            }
            BindingPattern::ArrayPattern(arr) => {
                for elem in arr.elements.iter().flatten() {
                    collect_binding(elem, out);
                }
                if let Some(rest) = &arr.rest {
                    collect_binding(&rest.argument, out);
                }
            }
            BindingPattern::AssignmentPattern(assign) => {
                collect_binding(&assign.left, out);
            }
        }
    }

    fn collect_all_exports(source: &str, source_type: SourceType) -> BTreeSet<String> {
        let allocator = Allocator::default();
        let parsed = Parser::new(&allocator, source, source_type).parse();
        assert!(
            parsed.diagnostics.is_empty(),
            "解析声明/源码出错：{:?}",
            parsed.diagnostics
        );
        let mut out = BTreeSet::new();
        for stmt in &parsed.program.body {
            match stmt {
                Statement::ExportDeclaration(decl) => match &decl.declaration {
                    Declaration::FunctionDeclaration(f) => {
                        if let Some(id) = &f.id {
                            out.insert(id.name.as_str().to_owned());
                        }
                    }
                    Declaration::ClassDeclaration(c) => {
                        if let Some(id) = &c.id {
                            out.insert(id.name.as_str().to_owned());
                        }
                    }
                    Declaration::VariableDeclaration(v) => {
                        for item in &v.declarations {
                            collect_binding(&item.id, &mut out);
                        }
                    }
                    Declaration::TSTypeAliasDeclaration(t) => {
                        out.insert(t.id.name.as_str().to_owned());
                    }
                    Declaration::TSInterfaceDeclaration(i) => {
                        out.insert(i.id.name.as_str().to_owned());
                    }
                    Declaration::TSEnumDeclaration(e) => {
                        out.insert(e.id.name.as_str().to_owned());
                    }
                    Declaration::TSNamespaceDeclaration(ns) => {
                        out.insert(ns.id.name.as_str().to_owned());
                    }
                    _ => {}
                },
                Statement::ExportNamedDeclaration(decl) => {
                    for spec in &decl.specifiers {
                        out.insert(spec.exported.name().as_str().to_owned());
                    }
                }
                Statement::ExportFromDeclaration(decl) => {
                    for spec in &decl.specifiers {
                        out.insert(spec.exported.name().as_str().to_owned());
                    }
                }
                _ => {}
            }
        }
        out
    }

    #[test]
    fn sdk_declarations_match_sdk_exports() {
        let runtime_exports =
            collect_all_exports(include_str!("plugins/sdk.tsx"), SourceType::tsx());
        let mut declared_exports = collect_all_exports(SDK_DECL, SourceType::d_ts());
        // `sdk.d.ts` 额外导出了供宿主类型收窄的纯 TS 类型。
        for ts_only in [
            "CommandSpec",
            "ContextMenuItemSpec",
            "HostEvent",
            "HostPathStyle",
            "LayoutMaterials",
            "LayoutSpec",
            "LocalizedText",
            "MenuItemSpec",
            "PageSpec",
            "StatusMenuIcon",
            "StatusMenuItemSpec",
            "StatusMenuSpec",
            "ViewSettingsEntry",
            "ViewSpec",
        ] {
            declared_exports.remove(ts_only);
        }
        let missing: Vec<_> = runtime_exports.difference(&declared_exports).collect();
        let extra: Vec<_> = declared_exports.difference(&runtime_exports).collect();
        assert!(
            missing.is_empty() && extra.is_empty(),
            "sdk.d.ts 与 sdk.tsx 导出不一致\n缺失：{missing:?}\n多余：{extra:?}"
        );
    }

    fn resolve_relative_dts(from: &str, specifier: &str) -> String {
        let mut parts: Vec<&str> = from.split('/').collect();
        parts.pop();
        for seg in specifier.split('/') {
            match seg {
                "." | "" => {}
                ".." => {
                    parts.pop();
                }
                other => parts.push(other),
            }
        }
        let joined = parts.join("/");
        if joined.ends_with(".d.ts") {
            joined
        } else {
            format!("{joined}.d.ts")
        }
    }

    #[test]
    fn generated_type_definitions_are_consistent_and_complete() {
        let defs: BTreeMap<String, String> = plugin_type_definitions(&[]).into_iter().collect();
        for required in [
            "nsh/index.d.ts",
            "nsh/types.d.ts",
            "nsh/base.d.ts",
            "nsh/desktop.d.ts",
            "nsh/i18n.d.ts",
            "nsh/jsx-runtime.d.ts",
            "nsh/globals.d.ts",
            "nsh/tokens.d.ts",
            "smelt/host.d.ts",
            "smelt/sdk.d.ts",
        ] {
            assert!(defs.contains_key(required), "缺少 {required}");
        }
        for forbidden in [
            "nsh/mobile.d.ts",
            "nsh/web.d.ts",
            "standard/index.d.ts",
            "standard/llrt-sources.d.ts",
            "os.d.ts",
            "process.d.ts",
            "fs/promises.d.ts",
        ] {
            assert!(!defs.contains_key(forbidden), "不应暴露 {forbidden}");
        }

        let globals = &defs["nsh/globals.d.ts"];
        assert!(!globals.contains("../standard/"), "{globals}");
        assert!(!globals.contains("import(\"buffer\")"), "{globals}");
        assert!(!globals.contains("import(\"process\")"), "{globals}");
        assert!(!globals.contains("import(\"crypto\")"), "{globals}");
        assert!(globals.contains("declare var console:"), "{globals}");
        assert!(globals.contains("declare function If<T>"), "{globals}");

        let sdk = &defs["smelt/sdk.d.ts"];
        assert!(sdk.contains("\"icons/plus.svg\""), "缺内建图标路径");
        assert!(
            sdk.contains("\"smelt-icons/agent-claude.svg\""),
            "缺智能体图标路径"
        );
        assert!(sdk.contains("\"session.list\""), "缺 ControlMethodName");
        assert!(sdk.contains("\"skills.scan\""), "缺 skills.scan");

        let tokens = &defs["nsh/tokens.d.ts"];
        for name in [
            "faint",
            "link",
            "need",
            "ok",
            "bad",
            "soft-hover",
            "row-selected",
        ] {
            assert!(
                tokens.contains(&format!("\"{name}\"")),
                "tokens.d.ts 缺 {name}"
            );
        }

        let host = &defs["smelt/host.d.ts"];
        assert!(host.contains("export declare const Icon:"), "{host}");
        assert!(host.contains("export declare const Vector:"), "{host}");
        assert!(host.contains("export declare const Smelt:"), "{host}");

        // 生成的声明必须能被 tsc 读懂：宿主模块的参数名原样进 .d.ts，`new` 这类保留字会让
        // 整个插件工程的类型检查在语法阶段就失败。
        for (path, body) in &defs {
            if !path.ends_with(".d.ts") {
                continue;
            }
            let allocator = Allocator::default();
            let parsed = Parser::new(&allocator, body, SourceType::d_ts()).parse();
            assert!(
                parsed.diagnostics.is_empty(),
                "{path} 解析出错：{:?}",
                parsed.diagnostics
            );
        }

        // 带上仓库 plugins/ 作为共享模块源时，必须产出 smelt/conversation.d.ts，
        // 且所有相对 import 与 /// <reference 均解析到实际生成文件。
        let repo_plugins = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../plugins");
        let with_modules: BTreeMap<String, String> =
            plugin_type_definitions(&[crate::manifest::SourceDir {
                path: repo_plugins.clone(),
                source: crate::manifest::PluginSource::Builtin,
                watch: false,
            }])
            .into_iter()
            .collect();
        assert!(
            with_modules.contains_key("smelt/conversation.d.ts"),
            "缺少共享模块声明 smelt/conversation.d.ts"
        );
        let conv_dts =
            collect_all_exports(&with_modules["smelt/conversation.d.ts"], SourceType::d_ts());
        let conv_tsx = collect_all_exports(
            &fs::read_to_string(repo_plugins.join("conversation/index.tsx")).unwrap(),
            SourceType::tsx(),
        );
        assert!(
            conv_dts.contains("SmeltConversation") && conv_tsx.contains("SmeltConversation"),
            "smelt/conversation 声明或实现缺少 SmeltConversation：{conv_dts:?} / {conv_tsx:?}"
        );

        // 每个相对 import 与 /// <reference 都必须落在实际生成的文件里，且导出的符号存在。
        for (path, body) in &with_modules {
            for line in body.lines() {
                if let Some(rest) = line.strip_prefix("/// <reference path=\"")
                    && let Some(target) = rest.strip_suffix("\" />")
                {
                    let resolved = resolve_relative_dts(path, target);
                    assert!(
                        with_modules.contains_key(&resolved),
                        "{path} 引用了不存在的文件：{target} ({resolved})"
                    );
                }
                if let Some(idx) = line.find("} from \"")
                    && let Some(rest) = line[..idx].split('{').nth(1)
                    && let Some(spec) = line[idx + "} from \"".len()..].strip_suffix("\";")
                {
                    let resolved = resolve_relative_dts(path, spec);
                    let target_body = with_modules.get(&resolved).unwrap_or_else(|| {
                        panic!("{path} 导入了不存在的模块：{spec} ({resolved})")
                    });
                    let exported = collect_all_exports(target_body, SourceType::d_ts());
                    for raw in rest.split(',') {
                        let name = raw
                            .trim()
                            .strip_prefix("type ")
                            .unwrap_or(raw.trim())
                            .split_whitespace()
                            .next()
                            .unwrap_or_default();
                        assert!(
                            exported.contains(name),
                            "{path} 从 {spec} 导入的 {name} 未在 {resolved} 中导出"
                        );
                    }
                }
            }
        }
    }

    #[test]
    fn write_plugin_types_is_idempotent_and_cleans_stale_files() {
        let dir = std::env::temp_dir().join(format!("smelt-nsh-types-{}", uuid::Uuid::new_v4()));
        fs::create_dir_all(&dir).unwrap();
        let stale = dir.join(".nsh/types/stale/old.d.ts");
        fs::create_dir_all(stale.parent().unwrap()).unwrap();
        fs::write(&stale, "// old").unwrap();

        let first = write_plugin_types(&dir, &[]).unwrap();
        assert!(first.files_written > 0);
        assert_eq!(first.files_unchanged, 0);
        assert!(first.created_tsconfig);
        assert!(!stale.exists(), "旧声明文件应当被清掉");
        assert!(dir.join("tsconfig.json").is_file());
        assert!(dir.join(".nsh/tsconfig.json").is_file());
        assert!(dir.join(".nsh/types/smelt/sdk.d.ts").is_file());

        // 用户自己的 tsconfig.json 不能被第二次 write_plugin_types 覆盖。
        let custom = r#"{"extends":"./.nsh/tsconfig.json","include":["src/**/*"]}"#;
        fs::write(dir.join("tsconfig.json"), custom).unwrap();
        let second = write_plugin_types(&dir, &[]).unwrap();
        assert_eq!(second.files_written, 0);
        assert!(second.files_unchanged > 0);
        assert!(!second.created_tsconfig);
        assert_eq!(
            fs::read_to_string(dir.join("tsconfig.json")).unwrap(),
            custom
        );

        let _ = fs::remove_dir_all(&dir);
    }
}
