/// 取一条文案，`params` 里的值填进 `%{名字}`。
export function t(key, params = {}) {
  const text = CATALOG[locale()]?.[key] ?? CATALOG.en[key] ?? key;
  return text.replace(/%\{(\w+)\}/g, (_, name) => String(params[name] ?? ""));
}

/// 按数量挑 `.one` / `.other`，`count` 也填进文案。
export function tn(key, count, params = {}) {
  return t(`${key}.${count === 1 ? "one" : "other"}`, { ...params, count });
}

/// 把几个名字连成一串，分隔符跟语言走。
export function list(names) {
  return names.join(t("list.separator"));
}
